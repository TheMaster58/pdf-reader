import { writeAnnotationsAsync } from '../pdf/annotClient';
import { fileNameOf, addRecent, pickSavePath, saveRecent, writeFileAtomic } from '../services/files';
import { loadPdf } from '../viewer/pdfjs';
import { useApp } from '../viewer/store';
import type { Annotation } from './model';
import { useAnnotations } from './store';

/**
 * The document exactly as it was opened. Every save rebuilds the file from these bytes plus the
 * current annotations, so repeated saves can never accumulate duplicates or drift.
 */
let baseline: Uint8Array | null = null;

export function setBaseline(bytes: Uint8Array | null): void {
  baseline = bytes;
}

let noticeTimer: ReturnType<typeof setTimeout> | undefined;

/** Shows a short confirmation ("Saved") that fades by itself. */
export function showNotice(message: string): void {
  clearTimeout(noticeTimer);
  useApp.setState({ notice: message });
  noticeTimer = setTimeout(() => useApp.setState({ notice: null }), 2500);
}

/**
 * Re-opens freshly generated bytes with PDF.js and checks they are sane before they replace
 * anything on disk: same page count, and every annotation we wrote is visible to a second reader.
 */
async function verifyGenerated(bytes: Uint8Array, expectedPages: number, annotations: Annotation[]): Promise<void> {
  const doc = await loadPdf(bytes.slice(), { requestPassword: async () => null });
  try {
    if (expectedPages > 0 && doc.numPages !== expectedPages) {
      throw new Error(`page count changed (${expectedPages} -> ${doc.numPages})`);
    }
    const pages = new Set(annotations.map((a) => a.pageIndex));
    for (const pageIndex of pages) {
      if (pageIndex >= doc.numPages) continue;
      const found = (await (await doc.getPage(pageIndex + 1)).getAnnotations()) as { subtype: string }[];
      const count = (subtype: string) => found.filter((f) => f.subtype === subtype).length;
      const wantHighlights = annotations.filter((a) => a.pageIndex === pageIndex && a.kind === 'highlight').length;
      const wantNotes = annotations.filter((a) => a.pageIndex === pageIndex && a.kind === 'note').length;
      if (count('Highlight') < wantHighlights || count('Text') < wantNotes) {
        throw new Error(`annotations on page ${pageIndex + 1} were not written correctly`);
      }
    }
  } finally {
    void doc.loadingTask.destroy();
  }
}

/**
 * Writes the document's highlights and notes into the PDF.
 * `saveAs` asks for a new location first. Returns true if the file on disk is now up to date.
 */
export async function saveCurrent(opts: { saveAs?: boolean } = {}): Promise<boolean> {
  const app = useApp.getState();
  const store = useAnnotations.getState();
  if (!baseline || app.status !== 'ready' || !app.filePath || app.annotationBlock || app.saving) return false;
  if (!opts.saveAs && !store.dirty) return true;

  let target = app.filePath;
  if (opts.saveAs) {
    const chosen = await pickSavePath(target);
    if (!chosen) return false;
    target = chosen;
  }

  // Edits made while the save is running must keep the document dirty afterwards.
  const snapshot = store.annotations;
  useApp.setState({ saving: true, error: null });
  try {
    const bytes = await writeAnnotationsAsync(baseline.slice(), snapshot);
    await verifyGenerated(bytes, app.pagesCount, snapshot);
    await writeFileAtomic(target, bytes);

    useAnnotations.getState().markSaved(snapshot);
    if (target !== app.filePath) {
      const recent = addRecent(useApp.getState().recent, target);
      saveRecent(recent);
      useApp.setState({ filePath: target, fileName: fileNameOf(target), recent });
    }
    showNotice('Saved');
    return true;
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err);
    useApp.setState({ error: `Could not save ${fileNameOf(target)}: ${message}` });
    return false;
  } finally {
    useApp.setState({ saving: false });
  }
}

/**
 * Call before anything that would discard the open document's annotations (opening another file,
 * closing the window). Resolves true if it is fine to go ahead: nothing unsaved, the user chose to
 * discard, or they chose to save and that worked.
 */
export async function ensureCanLeave(): Promise<boolean> {
  if (!useAnnotations.getState().dirty) return true;
  if (useApp.getState().unsavedPrompt) return false; // already asking

  const fileName = useApp.getState().fileName ?? 'this document';
  const choice = await new Promise<'save' | 'discard' | 'cancel'>((resolve) => {
    useApp.setState({
      unsavedPrompt: {
        fileName,
        resolve: (c) => {
          useApp.setState({ unsavedPrompt: null });
          resolve(c);
        },
      },
    });
  });
  if (choice === 'cancel') return false;
  if (choice === 'discard') return true;
  return saveCurrent();
}
